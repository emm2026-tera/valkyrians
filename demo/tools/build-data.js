// Optional: bundles data/*.json into data/data.js so the demo works when opened
// directly from disk (file://), where browsers block fetch() of local JSON.
// Usage: node demo/tools/build-data.js
const fs = require("fs");
const path = require("path");
const dir = path.join(__dirname, "..", "data");
const out = {};
for (const name of ["characters", "businesses", "accessories"]) {
  out[name] = JSON.parse(fs.readFileSync(path.join(dir, name + ".json"), "utf8"));
}
fs.writeFileSync(path.join(dir, "data.js"), "// AUTO-GENERATED by tools/build-data.js - do not edit.\nwindow.DOGZY_DATA = " + JSON.stringify(out, null, 2) + ";\n");
console.log("Wrote data/data.js");
